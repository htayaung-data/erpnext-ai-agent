	EXTRA_DOCKER_ARGS+=(-v "$ERPW_PROCUREMENT_PHASE7L_ASSET_ROOT:/phase7l-assets:ro")
	DOCKER_PROCUREMENT_PHASE7L_ASSET_ROOT="/phase7l-assets"
