	EXTRA_DOCKER_ARGS+=(-v "$ERPW_PROCUREMENT_PHASE7J2C_ASSET_ROOT:/phase7j2c-assets:ro")
	DOCKER_PROCUREMENT_PHASE7J2C_ASSET_ROOT="/phase7j2c-assets"
