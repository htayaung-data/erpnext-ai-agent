	EXTRA_DOCKER_ARGS+=(-v "$ERPW_PROCUREMENT_PHASE7K_ASSET_ROOT:/phase7k-assets:ro")
	DOCKER_PROCUREMENT_PHASE7K_ASSET_ROOT="/phase7k-assets"
