	EXTRA_DOCKER_ARGS+=(-v "${ERPW_WAREHOUSE_W3A_ASSET_ROOT}:/warehouse-w3a-assets:ro")
	DOCKER_WAREHOUSE_W3A_ASSET_ROOT="/warehouse-w3a-assets"
