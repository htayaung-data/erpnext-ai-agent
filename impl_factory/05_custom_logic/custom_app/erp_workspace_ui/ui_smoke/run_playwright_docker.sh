	EXTRA_DOCKER_ARGS+=(-v "${ERPW_WAREHOUSE_W3_ASSET_ROOT}:/warehouse-w3-assets:ro")
	DOCKER_WAREHOUSE_W3_ASSET_ROOT="/warehouse-w3-assets"
