def run_h3_discard_prefixed_question_restore_smoke() -> Dict[str, Any]:
	def _runner(doc) -> Dict[str, Any]:
		frappe.clear_cache()
		ok, first_payload = handle_qwen_user_message(
			session_name=doc.name,
			message="show me financial statement",
			user="Administrator",
		)
		if not ok:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: initial ambiguous statement request did not complete.")
		session_doc = frappe.get_doc(QWEN_SESSION_DOCTYPE, doc.name)
		first_assistant_text = str(_latest_assistant_payload(session_doc).get("text") or "").strip().lower()
		if not get_clarification_state(session_doc).has_pending:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: initial ambiguous statement request did not create pending clarification state.")
		if "profit & loss" not in first_assistant_text and "balance sheet" not in first_assistant_text and "cash flow" not in first_assistant_text:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: initial clarification did not expose the expected statement choices.")

		ok, second_payload = handle_qwen_user_message(
			session_name=doc.name,
			message='do u have customer name similar to "Nay Lin Mobile"?',
			user="Administrator",
		)
		second_mode = str((second_payload or {}).get("mode") or "").strip() or str((((second_payload or {}).get("agent_meta") or {}).get("mode")) or "").strip()
		if not ok or second_mode not in {"compiled_first_turn", "legacy_runtime", "legacy_runtime_rollout_fallback"}:
			raise RuntimeError(
				f"H3 discard-prefixed question-restore smoke failed: explicit customer query did not replace the pending statement branch in an approved lane. second_payload={second_payload!r}"
			)
		session_doc = frappe.get_doc(QWEN_SESSION_DOCTYPE, doc.name)
		if get_clarification_state(session_doc).has_pending:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: pending clarification survived the explicit customer override.")
		second_assistant_text = str(_latest_assistant_payload(session_doc).get("text") or "").strip().lower()
		if "ko nay lin mobile center" not in second_assistant_text:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: customer override answer did not resolve to Ko Nay Lin Mobile Center.")

		ok, third_payload = handle_qwen_user_message(
			session_name=doc.name,
			message="forget the first question, answer the last question",
			user="Administrator",
		)
		third_mode = str((third_payload or {}).get("mode") or "").strip() or str((((third_payload or {}).get("agent_meta") or {}).get("mode")) or "").strip()
		third_engine = str((((third_payload or {}).get("agent_meta") or {}).get("engine")) or "").strip()
		approved_third = third_mode in {"compiled_first_turn", "legacy_runtime", "legacy_runtime_rollout_fallback", "entity_drilldown"} or third_engine == "local_transform"
		if not ok or not approved_third:
			session_doc = frappe.get_doc(QWEN_SESSION_DOCTYPE, doc.name)
			tool_types = [
				str(item.get("type") or "").strip()
				for item in _session_tool_payloads(session_doc)
				if str(item.get("type") or "").strip()
			]
			raise RuntimeError(
				f"H3 discard-prefixed question-restore smoke failed: discard-prefixed answer-the-last-question did not stay in an approved bounded lane. third_payload={third_payload!r} tool_types={tool_types!r}"
			)
		session_doc = frappe.get_doc(QWEN_SESSION_DOCTYPE, doc.name)
		final_assistant_text = str(_latest_assistant_payload(session_doc).get("text") or "").strip()
		final_lower = final_assistant_text.lower()
		if "ko nay lin mobile center" not in final_lower:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: answer-the-last-question did not restore the newer customer focus.")
		if "profit & loss" in final_lower or "balance sheet" in final_lower or "cash flow" in final_lower or "which financial view would you like to see" in final_lower:
			raise RuntimeError("H3 discard-prefixed question-restore smoke failed: stale financial statement clarification leaked back after newer customer focus won.")
		final_grounded_turn = _latest_grounded_turn_contract(session_doc)
		final_reports = [
			str(value or "").strip()
			for value in (final_grounded_turn.get("artifact_source_reports") or [])
			if str(value or "").strip()
		]
		return {
			"ok": True,
			"second_mode": second_mode,
			"third_mode": third_mode,
			"third_engine": third_engine,
			"grounding_family_id": str((final_grounded_turn or {}).get("artifact_family_id") or "").strip(),
			"grounding_source_reports": final_reports,
			"answer_text": final_assistant_text,
		}

	return _run_phase6_smoke_session("H3 Discard-Prefixed Question Restore Smoke", _runner)



