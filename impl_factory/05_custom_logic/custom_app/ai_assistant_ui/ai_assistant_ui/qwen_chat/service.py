def _handle_prior_branch_restore_fresh_query(
	*,
	session_doc,
	request_id: str,
	session_id: str,
	user_id: str,
	site_name: str,
	raw_message: str,
	interaction_contract,
	conversation_control_evidence_contract,
	frontdoor_semantic_result,
	frontdoor_contract,
	clarification_response_contract,
	response_policy_contract,
	prior_branch_restore_contract,
	prior_branch_restore_control_decision_contract,
	additional_tool_payloads: List[Dict[str, Any]] | None = None,
):
	route_plan = _build_prior_branch_restore_fresh_query_plan_helper(
		request_id=request_id,
		prior_branch_restore_contract=prior_branch_restore_contract,
	)
	if not bool((route_plan or {}).get("handled")):
		return False, None
	synthesized_message = str((route_plan or {}).get("synthesized_message") or "").strip()
	governed_target_limit = int((route_plan or {}).get("governed_target_limit") or 0)
	followup_resolution = (route_plan or {}).get("followup_resolution")
	execution_path = (route_plan or {}).get("execution_path")
	scope_decision_contract = (route_plan or {}).get("scope_decision_contract")
	if not synthesized_message or followup_resolution is None or execution_path is None or scope_decision_contract is None:
		return False, None
	_append_message(session_doc, "user", raw_message)
	_append_tool_payload_values(
		session_doc,
		[
			interaction_contract,
			conversation_control_evidence_contract,
			frontdoor_semantic_result,
			frontdoor_contract,
			clarification_response_contract,
			*(additional_tool_payloads or []),
			prior_branch_restore_contract,
			prior_branch_restore_control_decision_contract,
			response_policy_contract,
			followup_resolution,
			scope_decision_contract,
			execution_path,
		],
	)
	compiled_result = execute_compiled_fresh_query_message(
		session_id=session_id,
		user_id=user_id,
		site_name=site_name,
		message=synthesized_message,
		recent_messages=[],
		clarification_resolution=clarification_response_contract.to_payload() if clarification_response_contract is not None else None,
		front_door_contract=frontdoor_contract.to_payload() if frontdoor_contract is not None else None,
		governed_target_limit=governed_target_limit,
	)
	_, payload = _handle_compiled_first_turn_result(
		session_doc=session_doc,
		request_id=request_id,
		interaction_contract=interaction_contract,
		followup_resolution=followup_resolution,
		execution_path=execution_path,
		governed_scope_contract=scope_decision_contract,
		front_door_contract=frontdoor_contract,
		clarification_response_contract=clarification_response_contract,
		result=compiled_result,
	)
	return True, payload


