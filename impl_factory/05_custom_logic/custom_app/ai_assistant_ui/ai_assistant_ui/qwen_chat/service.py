def _message_looks_like_self_contained_governed_business_query(
	*,
	message: str,
	language: str = "en",
) -> bool:
	text = " ".join(str(message or "").strip().lower().split())
	if not text:
		return False
	for term in governed_standalone_business_terms(language):
		clean = str(term or "").strip().lower()
		if clean and text == clean:
			return True
	for concept_id in ontology_detect_concepts(text, language=language, include_extended=False):
		if text in ontology_concept_aliases(str(concept_id or "").strip(), language=language):
			return True
	prefixes = [
		str(value or "").strip().lower()
		for value in ontology_self_contained_prefixes(language)
		if str(value or "").strip()
	]
	if prefixes and not any(text.startswith(prefix) for prefix in prefixes):
		return False
	if ontology_detect_concepts(text, language=language, include_extended=False):
		return True
	for term in governed_self_contained_business_terms(language):
		clean = str(term or "").strip().lower()
		if clean and re.search(rf"(?<!\\w){re.escape(clean)}(?!\\w)", text):
			return True
	return False


def _message_should_override_stale_context_as_fresh_query(
	*,
	message: str,
	language: str = "en",
) -> bool:
	"""Return True when a self-contained ERP request should not inherit old context."""

	if _message_has_grounded_context_anchor(message):
		return False
	return _message_looks_like_self_contained_governed_business_query(
		message=message,
		language=language,
	)


def _fresh_query_should_skip_pre_frontdoor_reasoning(
	*,
	fresh_governed_query_override_requested: bool,
	prior_offered_next_action_available: bool = False,
) -> bool:
	"""Fresh governed queries must not be swallowed by prior-artifact reasoning."""

	return bool(fresh_governed_query_override_requested and not prior_offered_next_action_available)


