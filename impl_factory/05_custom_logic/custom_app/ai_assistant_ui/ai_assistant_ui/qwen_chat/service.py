def _message_has_grounded_context_anchor(message: str) -> bool:
	text = " ".join(str(message or "").strip().lower().split())
	if not text:
		return False
	if re.search(r"\b(this|that|these|those|it|its|they|their|them)\b", text):
		return True
	return bool(
		re.search(
			r"\b(rank|row|no\.?|number)\s*\d+\b"
			r"|\b(the\s+)?(first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth|last)\s+"
			r"(customer|supplier|product|item|row|one|entry|document)\b",
			text,
		)
	)


def _frontdoor_recent_messages_for_message(
	*,
	message: str,
	recent_messages: List[Dict[str, str]] | None,
	grounded_context_available: bool,
	language: str = "en",
) -> List[Dict[str, str]]:
	recent = list(recent_messages or [])
	if not grounded_context_available:
		return recent
	if _message_has_grounded_context_anchor(message):
		return recent
	if _message_looks_like_self_contained_governed_business_query(
		message=message,
		language=language,
	):
		return []
	return recent


def _frontdoor_contract_handle_in_front_door(frontdoor_contract: Any) -> bool:
	if isinstance(frontdoor_contract, dict):
		return bool(frontdoor_contract.get("handle_in_front_door"))
	return bool(getattr(frontdoor_contract, "handle_in_front_door", False))


def _frontdoor_contract_intent_class(frontdoor_contract: Any) -> str:
	if isinstance(frontdoor_contract, dict):
		return str(frontdoor_contract.get("intent_class") or "").strip()
	return str(getattr(frontdoor_contract, "intent_class", "") or "").strip()


def _frontdoor_contract_has_direct_handling_authority(frontdoor_contract: Any) -> bool:
	"""True when the front-door contract already owns the turn response."""
	return _frontdoor_contract_handle_in_front_door(frontdoor_contract)


def _reasoning_activation_has_execution_authority(reasoning_semantic_result: Any) -> bool:
	if reasoning_semantic_result is None:
		return False
	if str(getattr(reasoning_semantic_result, "status", "") or "").strip() != "accepted":
		return False
	intent = getattr(reasoning_semantic_result, "intent", None)
	return bool(str(getattr(intent, "reasoning_type", "") or "").strip())


def _reasoning_contract_has_executable_offered_next_action(reasoning_contract: Dict[str, Any] | None) -> bool:
	contract = dict(reasoning_contract or {})
	if not contract:
		return False
	for action in contract.get("offered_next_actions") or []:
		if not isinstance(action, dict):
			continue
		if str(action.get("execution_mode") or "").strip() == "current_governed_artifact" and str(
			action.get("action_id") or ""
		).strip():
			return True
	return False


def _context_isolation_should_yield_to_prior_reasoning_action(
	*,
	context_isolation,
	reasoning_semantic_result: Any,
	latest_reasoning_contract: Dict[str, Any] | None,
) -> bool:
	if not bool(getattr(context_isolation, "force_new_query", False)):
		return False
	if bool(getattr(context_isolation, "out_of_scope", False)):
		return False
	if not _reasoning_contract_has_executable_offered_next_action(latest_reasoning_contract):
		return False
	if str(getattr(reasoning_semantic_result, "status", "") or "").strip() != "accepted":
		return False
	intent = getattr(reasoning_semantic_result, "intent", None)
	return str(getattr(intent, "reasoning_type", "") or "").strip() == "continuation_detail"


def _frontdoor_should_yield_to_reasoning_activation(
	*,
	reasoning_semantic_result: Any,
	latest_grounded_turn_available: bool,
	context_force_new_query: bool,
	entity_drilldown: Any = None,
) -> bool:
	if entity_drilldown is not None:
		return False
	if not latest_grounded_turn_available:
		return False
	if context_force_new_query:
		return False
	return _reasoning_activation_has_execution_authority(reasoning_semantic_result)


def _frontdoor_context_isolation_retry_needed(
	*,
	message: str,
	grounded_context_available: bool,
	frontdoor_contract: Any,
) -> bool:
	if not grounded_context_available:
		return False
	if _message_has_grounded_context_anchor(message):
		return False
	if not _frontdoor_contract_handle_in_front_door(frontdoor_contract):
		return False
	return _frontdoor_contract_intent_class(frontdoor_contract) in {
		"master_data_grain_clarification",
		"report_or_scope_clarification",
		"low_signal_non_business",
	}


def _should_skip_artifact_boundary(
	*,
	scope_decision_contract,
	message: str = "",
	language: str = "en",
	request_id: str = "",
	latest_grounded_turn: Dict[str, Any] | None = None,
	latest_family_artifact: Dict[str, Any] | None = None,
) -> bool:
	# Fresh-query breakouts must not be answered from the prior grounded artifact.
	if governed_scope_decision_requires_fresh_query(scope_decision_contract):
		return True
	if not _message_looks_like_self_contained_governed_business_query(
		message=message,
		language=language,
	):
		return False
	if _artifact_local_refinement_has_grounded_evidence(
		request_id=request_id or "artifact-boundary-skip-check",
		message=message,
		latest_grounded_turn=latest_grounded_turn or {},
		latest_family_artifact=latest_family_artifact or {},
	):
		return False
	return True


